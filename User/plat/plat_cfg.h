/**
 ****************************************************************************************************
 * @file        plat_cfg.h
 * @brief       平台配置：移植时只需要改这个文件 + 实现 plat_* 的函数
 *
 * 换平台要做的事：
 *   1. 改本文件的屏幕尺寸 / 缓冲数 / 对齐要求 / 是否跑在 OS 下
 *   2. 新写一个 plat_<platform>.c，实现 plat.h 里的函数
 *   3. 库代码（spine_api / spine_platform / raster2d / spine-cpp）一行都不用改
 ****************************************************************************************************
 */

#ifndef __PLAT_CFG_H
#define __PLAT_CFG_H

/*==================================================================================================
 * 运行模式
 *=================================================================================================*/

/**
 * PLAT_USE_RTOS
 *   0 = 裸机：等垂直回扫用轮询，延时用忙等/系统滴答
 *   1 = RTOS：等垂直回扫用信号量（LTDC 重装中断唤醒），延时用 OS 延时
 *
 * 打开后需要移植层额外实现 plat.h 里的 plat_os_* 钩子
 * （FreeRTOS 的现成实现见 User/plat/plat_os_freertos.c.template）
 */
#define PLAT_USE_RTOS           0

/** 分配器加锁：1 = 多任务共享 spine 堆时必须打开（裸机下自动为空） */
#define PLAT_ENABLE_MEM_LOCK    0

/*==================================================================================================
 * 显示
 *=================================================================================================*/

#define PLAT_SCREEN_W           800
#define PLAT_SCREEN_H           480
#define PLAT_FB_COUNT           3           /* 三缓冲 */

/*==================================================================================================
 * 纹理
 *=================================================================================================*/

#define PLAT_TEXTURE_ALIGN      4           /* 纹理首地址对齐（带硬件缩放的平台可能要 64）*/
#define PLAT_TEXTURE_MAX_W      1024
#define PLAT_TEXTURE_MAX_H      1024

/*==================================================================================================
 * 能力开关
 *=================================================================================================*/

#define PLAT_HAS_DCACHE         1           /* 1 = 需要 CPU 手动维护缓存 */
#define PLAT_PRESENT_BLOCKING   1           /* 1 = plat_fb_present 会等到切换安全生效 */

#endif /* __PLAT_CFG_H */
